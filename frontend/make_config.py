"""Write frontend/config.js from .env, so index.html has no config UI.

The call endpoint (a presign Lambda URL, or a ws:// URL when running
agentcore_app/strands_agent.py locally) is deployment config, not something a
caller should type into the page — it belongs in .env with everything else.

index.html is opened straight from disk (file://), where a page can't read
.env, or fetch() anything next to it. So this writes the one value it needs
into a tiny generated script the page loads instead:

    CALL_ENDPOINT in .env  ->  window.AVA_CONFIG.callEndpoint in config.js

Run it after editing .env:

    python frontend/make_config.py

config.js is gitignored — it's generated, and holds one deployment's URL.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from dotenv import dotenv_values

ENV_KEY = "CALL_ENDPOINT"
REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = REPO_ROOT / ".env"
OUTPUT_PATH = Path(__file__).resolve().parent / "config.js"


def main() -> int:
    if not ENV_PATH.exists():
        print(f"error: no {ENV_PATH} — copy .env.example to .env first", file=sys.stderr)
        return 1

    endpoint = (dotenv_values(ENV_PATH).get(ENV_KEY) or "").strip()
    if not endpoint:
        print(
            f"error: {ENV_KEY} is not set in {ENV_PATH}\n"
            "  Set it to your presign Lambda's Function URL, or to\n"
            "  ws://127.0.0.1:8080/ws when running strands_agent.py locally.",
            file=sys.stderr,
        )
        return 1

    # json.dumps, not an f-string: this value lands inside a JS source file, so
    # quotes/backslashes in it have to be escaped rather than pasted verbatim.
    OUTPUT_PATH.write_text(
        "// Generated by frontend/make_config.py from .env — do not edit.\n"
        f"window.AVA_CONFIG = {{ callEndpoint: {json.dumps(endpoint)} }};\n"
    )
    print(f"wrote {OUTPUT_PATH.relative_to(REPO_ROOT)} — {ENV_KEY}={endpoint}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
