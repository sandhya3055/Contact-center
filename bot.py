# One id per bot.py run, stands in for a real call/session id since there's
# no telephony system here. Auto-injected into whichever tool requires a
# session_id (see _instrument_tools) — Ava never sees or has to invent this.
CALL_SESSION_ID = str(uuid.uuid4())

# PII tokenization for logs only (see _build_pii_redactor below). Nova Sonic
# is a speech-to-speech model — the caller's own audio already carries their
# mobile number, and Ava's job this call is to read it and other identifiers
# back to them, so there's no way to redact these from what reaches the
# model without breaking the conversation. What IS fully our own and fully
# fixable is this process's logs (stdout here, CloudWatch once deployed) —
# _instrument_tools' [tool call]/[tool result] lines used to print raw
# arguments and results; they're tokenized before logging from here on. The
# real values still flow to the gateway tool and to Nova Sonic unchanged.
_SENSITIVE_FIELD_HINTS = (
    "mobile", "phone", "email", "address", "aadhaar", "pan", "ssn",
    "national_id", "account_number", "card_number", "dob", "birth",
    "policy", "vehicle", "registration", "reg_no", "vin",
)

_PHONE_PATTERN = re.compile(r"(?<!\w)\+?\d[\d\-\s]{7,14}\d(?!\w)")


def _is_sensitive_field(key: str) -> bool:
    key_lower = key.lower()
    return any(hint in key_lower for hint in _SENSITIVE_FIELD_HINTS)


def _build_pii_redactor():
    """Returns a `redact(value)` function for use in log lines only.

    Tokens are stable per real value for the life of this call (the same
    mobile number always logs as the same token), generated by hashing the
    value — not the sequence it was seen in — so two independent redactors
    (e.g. one per call) never need to agree on ordering. The token -> real
    value mapping lives only in this closure's memory: never written to
    disk, never logged itself, and gone as soon as this call ends.
    """

    tokens: dict[str, str] = {}
    reverse: dict[str, str] = {}

    def tokenize(value: str) -> str:
        token = tokens.get(value)
        if token is None:
            digest = hashlib.sha256(value.encode()).hexdigest()[:8]
            token = f"[PII_{digest}]"
            tokens[value] = token
            reverse[token] = value
        return token

    def redact(data):
        if isinstance(data, dict):
            return {
                key: tokenize(str(value)) if _is_sensitive_field(key) and value is not None else redact(value)
                for key, value in data.items()
            }
        if isinstance(data, list):
            return [redact(item) for item in data]
        if isinstance(data, str):
            return _PHONE_PATTERN.sub(lambda m: tokenize(m.group(0)), data)
        return data

    return redact


# Untrusted tool output (G2.18): a tool result comes from the gateway's
# backend, not from the caller or the model — but it's still external input
# that could be malformed, compromised, or (for a third-party MCP server)
# actively poisoned with text aimed at the model rather than data for it.
# Nova Sonic's tool-result API takes a JSON object, not a text block, so the
# usual "wrap it in delimiters and tell the model it's data" defense doesn't
# apply structurally here — this instead scans every string value in a
# parsed tool result for instruction-like phrasing and neutralizes it before
# it ever reaches original_callback (i.e. before Nova Sonic sees it). It's a
# heuristic, not a classifier: cheap insurance against the tool result
# smuggling a directive, not a guarantee against a determined attacker.
_INJECTION_PATTERNS = [
    re.compile(pattern, re.IGNORECASE)
    for pattern in (
        r"ignore (all|any|the)?\s*(previous|prior|above)\s*instructions",
        r"disregard (all|any|the)?\s*(previous|prior|above)",
        r"new (system )?instructions",
        r"you are now (a|an)",
        r"system\s*:\s*\S",
        r"reveal (the|your) (system prompt|instructions)",
    )
]


def _looks_like_injection(text: str) -> bool:
    return any(pattern.search(text) for pattern in _INJECTION_PATTERNS)


def _sanitize_untrusted(data):
    """Recursively neutralize instruction-like strings in tool-returned data
    (or a tool's own description) — see the note above _INJECTION_PATTERNS."""
    if isinstance(data, dict):
        return {key: _sanitize_untrusted(value) for key, value in data.items()}
    if isinstance(data, list):
        return [_sanitize_untrusted(item) for item in data]
    if isinstance(data, str) and _looks_like_injection(data):
        logger.warning(f"[untrusted-output] neutralized suspicious content: {data[:80]!r}...")
        return "[content removed: this looked like an embedded instruction, not data]"
    return data


# Client-side half of idempotency (G1.19): if the exact same tool call
# (same arguments) repeats within this window — a dropped acknowledgement,
# a confused retry — the first call's result is replayed instead of
# executing the action again. Bounded by time rather than kept for the
# whole call so a genuinely new, later call with coincidentally identical
# arguments (e.g. re-checking status) still gets a fresh execution rather
# than being served stale data forever. This is the client's contribution;
# true dedup still depends on the gateway tool itself being safe to retry.
IDEMPOTENCY_WINDOW_SECONDS = 30

# Human-in-the-loop threshold (G4.19): a claim at or above this estimated
# cost must not be registered autonomously, however confident Ava is —
# confirmed with the team as the business threshold. Detected generically
# by the presence of HIGH_VALUE_CLAIM_FIELD in a call's arguments, not by
# hardcoding a tool name, so this keeps working if the gateway renames or
# adds a second tool that also takes an estimated_cost. SYSTEM_INSTRUCTION
# also tells Ava about the threshold so she can set expectations with the
# caller before even attempting the call, but this check below is what
# makes it non-negotiable regardless of what the model decides.
HIGH_VALUE_CLAIM_FIELD = "estimated_cost"
HIGH_VALUE_CLAIM_THRESHOLD = 100_000


SYSTEM_INSTRUCTION = """
You are Ava, the AI assistant for the contact center. You speak with callers
over voice, so keep every response short, natural, and conversational — a
sentence or two at a time. Never use lists, headings, or symbols that can't
be spoken aloud.

At the very start of the conversation, introduce yourself in one short
sentence, then ask for the caller's mobile number:
"Hi, I'm Ava, your AI Assistant. I can look at your policy, answer general
questions, register a claim, or connect you with a human agent. First,
could I get your mobile number?"

Your tools come from the gateway, and each one's own description tells you
exactly what it does and what it needs — read those descriptions, don't
assume. In general terms, you can look up a caller's policy by mobile
number, register a claim against a verified policy, and escalate to a human
agent. Decide for yourself, from what the caller actually says, which tool
to use and when — there is no fixed script to follow.

Looking up a policy by mobile number doubles as your identity check —
there's no separate verification step or date of birth needed: a caller who
confirms a mobile number matching an active policy is treated as verified
for that policy. Long digit sequences spoken one at a time are easy to
mishear (a trailing digit especially can get dropped), so read the number
back digit by digit and get an explicit yes before calling the lookup tool,
the same way you'd confirm any other critical detail (a claim's incident
date, a vehicle registration) before submitting it. If the caller doesn't
clearly say yes but instead corrects you or restates the number, that
restatement is itself unconfirmed — read the new version back and ask again,
and keep looping until you get an explicit yes. Never call the lookup tool
on a number you haven't had confirmed back to you. Look up the policy before
discussing policy details or accepting a claim, and don't ask the caller to
re-verify later in the same call. If no policy is found, double-check the
number was heard correctly before telling the caller. If a caller has more
than one policy or vehicle, ask which one the call is about before
continuing.

Any identifier you say aloud — a policy number, claim number, vehicle
registration, or similar code — should be spoken one character at a time
(e.g. "three two three one four", not "three thousand two hundred and
thirty-one"), the same way you already do for mobile numbers. This applies
whether you're reading one back to confirm it or stating one to the caller.

When the caller wants to register a claim, check first: the policy lookup
may already show an existing or open claim on that policy or vehicle — read
it before asking anything else. If one is already there, tell the caller
right away and share whatever claim id or status you have, instead of
collecting a full set of incident details first and only then discovering
it's a duplicate. Only move on to collecting new details if there's
genuinely no existing claim, or the caller makes clear this is a separate,
new incident. This same check-before-you-ask habit applies to any action,
not just claims: confirm what's already true before running the caller
through questions whose answers might turn out not to matter.

When registering a claim, use the policy id and vehicle details from the
lookup — don't take a policy id the caller just states blind. Read the
details back to confirm before submitting. If the claim tool itself reports
one already exists — found only at that point, after you've already asked
for details — stop there: don't ask the caller to repeat anything, just
tell them what's already on file.

If a claim's estimated cost is ₹1,00,000 or more, you cannot register it
yourself no matter how straightforward it seems — tell the caller a
specialist needs to review a claim of that size, and escalate them to a
human agent with the details you've already gathered, the same way you
would for any other escalation.

Use your judgment on when to escalate to a human agent: the caller directly
asks for a person, their request is outside what your tools can help with,
a tool keeps failing, or the caller sounds frustrated or unsatisfied after
a couple of attempts. When you do, summarize what the caller wants and what
you've already found out so the human agent has full context and the
caller never has to repeat themselves. After escalating, tell the caller —
in your own words — that you're connecting them with a teammate who has the
full picture.

Never fabricate policy, claim, or account information. If you're unsure what
the caller means, ask a clarifying question rather than guessing.
""".strip()


def _instrument_tools(tools: ToolsSchema) -> ToolsSchema:
    """Wrap every MCP tool handler: log its call/result, fix up the result
    type, and auto-inject a session_id into whichever tool needs one.

    Nothing here is tied to a specific tool's name — a tool is detected as
    needing a session_id generically, by checking whether its own live
    schema requires one, not by a hardcoded tool-name constant. So if the
    gateway adds, removes, or reshapes tools, this keeps working unchanged.

    Three things happen here, all at the same boundary:

    1. Logging — print which tool Ava called, with what arguments, and what
       it returned, so the terminal shows exactly what's happening instead
       of a black box.
    2. JSON parsing — Pipecat's MCP client always hands back a tool's result
       as a JSON-text string (that's just how MCP content works). AWS Nova
       Sonic only JSON-encodes a tool result if it's already a Python dict —
       a string gets sent through as-is, which AWS then rejects
       ("Unsupported JSON type in Tool Result. Please provide the Tool
       Result as a JSON object"). Parsing the string back into an object
       here, once, fixes it for every tool.
    3. session_id injection — hidden from the schema the LLM sees (removed
       from both properties and required) and merged into the arguments
       right before the call, for any tool whose gateway-advertised schema
       lists session_id as required.

    A fourth thing happens across ALL tool calls sharing this ToolsSchema:
    argument grounding. Any argument whose name matches a field some earlier
    tool call this session actually returned must equal a value that field
    actually held — it cannot be a value Ava made up or took directly from
    what the caller said. E.g. a claim tool's policy_id must equal what the
    lookup tool returned, not a number Ava merely heard. This enforces
    SYSTEM_INSTRUCTION's "use the id from the lookup" rule as a runtime check
    the model cannot reason its way around, detected generically by field
    name (grounded_values, populated from every successful tool result) —
    not by hardcoding which tool or field this applies to. A field no tool
    has ever returned is never gated, so caller-stated fields (a claim type,
    an incident date) always pass through untouched.

    The logging in (1) is itself tokenized via _build_pii_redactor (see its
    docstring) — the [tool call]/[tool result] lines never print a real
    mobile number, policy id, or vehicle registration, only a stable token.
    Only the log lines are affected; original_callback/original_handler
    below always receive the real, unredacted values.

    Two more things happen per tool call, each scoped to its own tool (a
    fresh idempotency_cache per with_instrumentation call, i.e. per tool):

    5. Idempotency (G1.19) — an exact repeat of the same arguments within
       IDEMPOTENCY_WINDOW_SECONDS returns the first call's result instead of
       invoking the tool again, so a dropped acknowledgement or a confused
       retry can't double a side effect like registering a claim.
    6. Untrusted output (G2.18) — every tool result is passed through
       _sanitize_untrusted before grounding, caching, logging, or reaching
       Nova Sonic, so a malformed or compromised gateway response can't
       smuggle an instruction into the conversation as if it were data.
    7. High-value HITL gate (G4.19) — a call whose HIGH_VALUE_CLAIM_FIELD
       argument meets or exceeds HIGH_VALUE_CLAIM_THRESHOLD is blocked
       before it executes; the model gets back a structured result telling
       it to escalate to a human instead. This is checked first, before
       idempotency or grounding, since a call this policy rejects should
       never reach — or be cached by — either of those.
    """

    grounded_values: dict[str, set[str]] = {}
    redact_for_log = _build_pii_redactor()

    def with_instrumentation(schema, original_handler):
        needs_session_id = "session_id" in schema.required
        idempotency_cache: dict[str, tuple[float, Any]] = {}

        async def wrapped(params):
            cost = params.arguments.get(HIGH_VALUE_CLAIM_FIELD)
            if isinstance(cost, (int, float)) and cost >= HIGH_VALUE_CLAIM_THRESHOLD:
                logger.warning(
                    f"[hitl required] {params.function_name} blocked — "
                    f"{HIGH_VALUE_CLAIM_FIELD}={cost} >= {HIGH_VALUE_CLAIM_THRESHOLD}"
                )
                await params.result_callback(
                    {
                        "error": "human_approval_required",
                        "message": (
                            f"Cannot register this claim automatically: its {HIGH_VALUE_CLAIM_FIELD} "
                            f"({cost}) is at or above the {HIGH_VALUE_CLAIM_THRESHOLD} threshold that "
                            "requires human approval. Do not retry this call. Tell the caller a "
                            "specialist needs to review a claim of this size, and escalate them to a "
                            "human agent with the claim details you've already gathered."
                        ),
                    }
                )
                return

            cache_key = json.dumps(params.arguments, sort_keys=True, default=str)
            cached = idempotency_cache.get(cache_key)
            now = time.monotonic()
            if cached is not None and now - cached[0] < IDEMPOTENCY_WINDOW_SECONDS:
                logger.info(
                    f"[idempotency] {params.function_name} — repeat of a call from "
                    f"{now - cached[0]:.1f}s ago, returning its cached result instead of re-executing"
                )
                await params.result_callback(cached[1])
                return

            ungrounded = [
                key
                for key, value in params.arguments.items()
                if key in grounded_values and str(value) not in grounded_values[key]
            ]
            if ungrounded:
                logger.warning(
                    f"[grounding blocked] {params.function_name} args {ungrounded} "
                    "were not returned by a completed lookup this call"
                )
                await params.result_callback(
                    {
                        "error": "ungrounded_argument",
                        "fields": ungrounded,
                        "message": (
                            f"Cannot proceed: {', '.join(ungrounded)} must come from a completed "
                            "lookup earlier in this call, not be restated from what the caller said. "
                            "Run the lookup tool again and use its returned value."
                        ),
                    }
                )
                return

            if needs_session_id:
                params.arguments = {**params.arguments, "session_id": CALL_SESSION_ID}
            logger.info(f"[tool call] {params.function_name}({redact_for_log(params.arguments)})")
            original_callback = params.result_callback

            async def parsing_callback(result, **kwargs):
                if isinstance(result, str):
                    try:
                        result = json.loads(result)
                    except (json.JSONDecodeError, TypeError):
                        pass
                result = _sanitize_untrusted(result)
                if isinstance(result, dict):
                    for key, value in result.items():
                        if isinstance(value, (str, int, float)):
                            grounded_values.setdefault(key, set()).add(str(value))
                idempotency_cache[cache_key] = (now, result)
                logger.info(f"[tool result] {params.function_name} -> {redact_for_log(result)}")
                await original_callback(result, **kwargs)

            params.result_callback = parsing_callback
            await original_handler(params)

        return wrapped

    return ToolsSchema(
        standard_tools=[
            FunctionSchema(
                name=schema.name,
                description=_sanitize_untrusted(schema.description),
                properties={k: v for k, v in schema.properties.items() if k != "session_id"},
                required=[r for r in schema.required if r != "session_id"],
                handler=with_instrumentation(schema, schema.handler),
            )
            for schema in tools.standard_tools
        ]
    )


async def main():
    missing = [
        var
        for var in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY")
        if not os.getenv(var)
    ]
    if missing:
        logger.error(
            f"Missing required env var(s): {', '.join(missing)}. "
            "Copy .env.example to .env and fill it in."
        )
        sys.exit(1)

    logger.info(f"Connecting to MCP gateway at {MCP_SERVER_URL} (via mcp-proxy-for-aws) ...")
    # MCP_SERVER_URL is a SigV4-protected AWS Bedrock AgentCore Gateway endpoint,
    # not an open MCP server — Pipecat's MCPClient only speaks plain
    # StreamableHttpParameters (no request signing), so we spawn AWS's own
    # mcp-proxy-for-aws as a local stdio subprocess in front of it. The proxy
    # signs every request with local AWS credentials; MCPClient just talks
    # stdio to the proxy like it would to any other local MCP server.
    aws_env = {
        key: os.environ[key]
        for key in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "AWS_REGION")
        if os.getenv(key)
    }
    mcp = MCPClient(
        server_params=StdioServerParameters(
            command="mcp-proxy-for-aws",
            args=[MCP_SERVER_URL, "--service", "bedrock-agentcore", "--region", AWS_REGION],
            env=aws_env,
        ),
    )
    tools = _instrument_tools(await mcp.tools())
    logger.info(
        "MCP tools loaded: "
        + ", ".join(f"{t.name} — {t.description.strip().splitlines()[0]}" for t in tools.standard_tools)
    )

    transport = LocalAudioTransport(
        LocalAudioTransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
            # Suppresses background/mic noise from the caller's audio before
            # it reaches Nova Sonic — runs locally, no API key needed.
            audio_in_filter=RNNoiseFilter(),
        )
    )

    llm = AWSNovaSonicLLMService(
        access_key_id=os.environ["AWS_ACCESS_KEY_ID"],
        secret_access_key=os.environ["AWS_SECRET_ACCESS_KEY"],
        session_token=os.getenv("AWS_SESSION_TOKEN"),
        region=AWS_REGION,
        settings=AWSNovaSonicLLMService.Settings(
            system_instruction=SYSTEM_INSTRUCTION,
            voice="tiffany",  # matthew, tiffany, amy, and others — see AWS Nova Sonic voice docs
        ),
        tools=tools,
    )

    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(context)

    pipeline = Pipeline(
        [
            transport.input(),
            user_aggregator,
            llm,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(enable_metrics=True, enable_usage_metrics=True),
        processor_unusable_policy=ProcessorUnusablePolicy.END,
    )

    runner = WorkerRunner(handle_sigint=False if sys.platform == "win32" else True)
    await runner.add_workers(worker)

    @user_aggregator.event_handler("on_user_turn_message_added")
    async def on_user_turn_message_added(aggregator, message: UserTurnMessageAddedMessage):
        logger.info(f"You: {message.content}")

    @assistant_aggregator.event_handler("on_assistant_turn_stopped")
    async def on_assistant_turn_stopped(aggregator, message: AssistantTurnStoppedMessage):
        logger.info(f"Ava: {message.content}")

    async def kick_off():
        # Local mic/speaker audio has no "client connected" event to hook,
        # so nudge Ava to open with her introduction shortly after startup.
        await asyncio.sleep(1)
        context.add_message(
            {"role": "developer", "content": "Greet the caller now with your introduction."}
        )
        await worker.queue_frames([LLMRunFrame()])

    logger.info("Ava is listening. Speak into your microphone. Press Ctrl+C to stop.")
    await asyncio.gather(runner.run(), kick_off())


if __name__ == "__main__":
    asyncio.run(main())
